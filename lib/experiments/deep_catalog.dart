import 'experiment_model.dart';

/// A prediction and an independent explanation are both required.
ExperimentSpec reasoningLesson({
  required String id,
  required String title,
  required String stage,
  required String knowledge,
  required String prompt,
  required List<String> choices,
  required int answer,
  required List<String> reasons,
  required int reason,
  required String hint,
  required String explanation,
  required String source,
  String? code,
  List<int>? swatches,
}) => ExperimentSpec(
  id: id,
  title: title,
  stage: stage,
  mechanism: 'reasonedChoice',
  prompt: prompt,
  hint: hint,
  explanation: explanation,
  skillIds: [id],
  initial: {'answer': -1, 'reason': -1},
  config: {
    'knowledge': knowledge,
    'choices': choices,
    'reasons': reasons,
    'source': source,
    'code': ?code,
    'swatches': ?swatches,
  },
  validator: (data) => data['answer'] == answer && data['reason'] == reason,
  evaluator: (data) {
    final a = data['answer'], r = data['reason'];
    if (a is! int ||
        r is! int ||
        a < 0 ||
        a >= choices.length ||
        r < 0 ||
        r >= reasons.length) {
      return const EvaluationResult(
        isCorrect: false,
        feedbackKey: 'invalid-state',
      );
    }
    return EvaluationResult(
      isCorrect: a == answer && r == reason,
      satisfiedConstraints: [
        if (a == answer) 'answer',
        if (r == reason) 'reason',
      ],
      feedbackKey: a != answer
          ? 'rethink-answer'
          : r != reason
          ? 'rethink-reason'
          : 'correct',
    );
  },
);

