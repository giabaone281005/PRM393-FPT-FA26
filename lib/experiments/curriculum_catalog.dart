import 'experiment_model.dart';
import 'curriculum_engine.dart';

ExperimentSpec _activity(
  String id,
  String title,
  String prompt,
  String explanation,
  String mechanism,
  ExperimentData config,
  ExperimentData initial, {
  String stage = 'Vận dụng',
  String hint = 'Đọc từng điều kiện, thử một thay đổi rồi đối chiếu mô hình.',
}) => ExperimentSpec(
  id: id,
  title: title,
  prompt: prompt,
  hint: hint,
  explanation: explanation,
  mechanism: mechanism,
  config: config,
  initial: initial,
  stage: stage,
  skillIds: ['${id.split('-').first}.transfer'],
  validator: (d) => evaluateCurriculum(mechanism, config, d).isCorrect,
  evaluator: (d) => evaluateCurriculum(mechanism, config, d),
);

ExperimentSpec _connect(
  String id,
  String title,
  String prompt,
  List<String> items,
  List<String> choices,
  List<int> target,
  String explanation, {
  String mechanism = 'matchPairs',
  String stage = 'Nền tảng',
  String? passage,
}) => _activity(
  id,
  title,
  prompt,
  explanation,
  mechanism,
  {'items': items, 'choices': choices, 'target': target, 'passage': ?passage},
  {'values': List.filled(items.length, -1)},
  stage: stage,
  hint: mechanism == 'clozeBank'
      ? 'Đọc cả câu trước và sau chỗ trống; mỗi từ phải đúng cả nghĩa và ngữ cảnh.'
      : 'Ghép theo quan hệ được hỏi; không dựa vào vị trí của thẻ.',
);
ExperimentSpec _order(
  String id,
  String title,
  String prompt,
  List<String> items,
  List<int> target,
  String explanation, {
  String stage = 'Vận dụng',
}) => _activity(
  id,
  title,
  prompt,
  explanation,
  'sequenceTiles',
  {'items': items, 'target': target},
  {'values': List.generate(items.length, (i) => i)},
  stage: stage,
  hint: 'Dùng mũi tên hoặc kéo thẻ để đổi thứ tự; kiểm tra quan hệ trước–sau.',
);
ExperimentSpec _evidence(
  String id,
  String title,
  String prompt,
  List<String> items,
  List<int> target,
  String explanation, {
  String stage = 'Thử thách',
}) => _activity(
  id,
  title,
  prompt,
  explanation,
  'evidenceBoard',
  {'items': items, 'target': target},
  {'selected': <int>[]},
  stage: stage,
  hint: 'Có thể chọn nhiều thẻ. Phân biệt dữ kiện quan sát được với ý kiến và kết luận vượt bằng chứng.',
);
ExperimentSpec _lab(
  String id,
  String title,
  String prompt,
  String x,
  String y,
  int goal,
  String explanation,
) => _activity(
  id,
  title,
  '$prompt Mô hình giản lược: kết quả = $x × $y. Mỗi tham số từ 0 đến 3. Tạo kết quả $goal, dự đoán rồi chạy thử.',
  explanation,
  'causalExperiment',
  {
    'axes': [x, y],
    'goal': goal,
  },
  {
    'x': 0,
    'y': 0,
    'prediction': -1,
    'observed': <int>[],
    'trials': <dynamic>[],
  },
  stage: 'Thử thách',
  hint: 'Đổi một yếu tố mỗi lần để nhìn rõ tác động. Ghi nhớ giới hạn 0–3.',
);
ExperimentSpec _budget(
  String id,
  String title,
  String prompt,
  List<String> items,
  List<int> minima,
  String explanation,
) => _activity(
  id,
  title,
  '$prompt Phân bổ đúng 10 đơn vị; mỗi mục phải đạt mức tối thiểu ghi bên dưới.',
  explanation,
  'resourceBudget',
  {'items': items, 'minima': minima},
  {'values': List.filled(items.length, 0)},
  stage: 'Thử thách',
  hint: 'Đáp ứng các mức tối thiểu trước, rồi phân bổ phần còn lại. Có thể có nhiều phương án đúng.',
);
ExperimentSpec _listen(
  String id,
  String title,
  String text,
  List<String> choices,
  int target,
  String explanation, {
  String stage = 'Nền tảng',
}) => _activity(
  id,
  title,
  'Nghe câu tiếng Anh rồi chọn ý đúng. Có thể nghe chậm, nghe lại hoặc mở bản chữ.',
  explanation,
  'listeningChoice',
  {'text': text, 'choices': choices, 'target': target},
  {'answer': -1, 'experienced': false},
  stage: stage,
  hint: 'Chú ý hành động, thời gian và những từ phủ định trong câu.',
);
ExperimentSpec _speak(
  String id,
  String title,
  String prompt,
  String text,
  List<String> accepted,
  String explanation, {
  String stage = 'Vận dụng',
}) => _activity(
  id,
  title,
  prompt,
  explanation,
  'speechPractice',
  {'text': text, 'accepted': accepted},
  {'response': ''},
  stage: stage,
  hint:
      'Nghe câu mẫu, nói từng cụm ngắn. Có thể nhập câu nếu không dùng micro.',
);

